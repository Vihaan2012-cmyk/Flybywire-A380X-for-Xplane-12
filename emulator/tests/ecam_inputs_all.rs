//! `SimVar.GetSimVarValue('L:NAME', ...)` API in some places and the newer
//! `RegisteredSimVar.create('L:NAME', ...)` API in others). This test
//! checks the true deduplicated set of 388 rather than re-testing 271
//! names twice.
//!
//! Matching mirrors `Snapshot::find` (src/lib.rs): a name is PRESENT if it
//! (or its `A32NX_`-prefixed/unprefixed counterpart) is a key in
//! `snapshot_all()`.

