const NAME_PREFIX: &str = "A32NX_";

fn present(names: &std::collections::HashSet<&str>, want: &str) -> bool {
    if names.contains(want) {
        return true;
    }
    match want.strip_prefix(NAME_PREFIX) {
        Some(bare) => names.contains(bare),
        None => names.contains(format!("{NAME_PREFIX}{want}").as_str()),
    }
}

#[test]
fn all_fws_inputs_present_or_absent() {
    let mut e = presets::engines_running();
    for _ in 0..200 {
        e.tick(0.05);
    }
    let snapshot = e.snapshot_all();
    let names: std::collections::HashSet<&str> = snapshot.iter().map(|(n, _)| n.as_str()).collect();

    let mut present_list = Vec::new();
    let mut absent_list = Vec::new();
    for &want in ALL_FWS_INPUTS {
        if present(&names, want) {
            present_list.push(want);
        } else {
            absent_list.push(want);
        }
    }

    eprintln!(
        "=== FWS inputs: {} total, {} PRESENT, {} ABSENT ===",
        ALL_FWS_INPUTS.len(),
        present_list.len(),
        absent_list.len()
    );
    eprintln!("--- ABSENT ({}) ---", absent_list.len());
    for a in &absent_list {
        eprintln!("{a}");
    }
    // Informational only -- this test always passes; its job is the
    // eprintln! dump above, captured with --nocapture. It should never
    // regress silently, so it still fails hard if the emulator itself
    // can't build a running aircraft at all.
    assert!(!present_list.is_empty() || !absent_list.is_empty());
}
